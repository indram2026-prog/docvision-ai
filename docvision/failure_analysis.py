"""Failure analysis: turn raw FN/FP lists into causes, counts and annotated examples (results/FAILURES.md).

  python -m docvision.failure_analysis --results results [--pdf some.pdf]

Cause taxonomy for every unmatched box (same-class IoU<0.5):
  confusion      a missed GT box overlaps a predicted box of ANOTHER class (e.g. title read as heading)
  localisation   a missed GT box overlaps a predicted box of the SAME class at IoU<0.5 (boundary wrong)
  missed         nothing overlaps (detector silent)
  spurious       a predicted box overlaps no GT box (hallucination)
"""
from __future__ import annotations
import argparse, json, os
from collections import Counter, defaultdict
from .schema import iou


def classify(errors):
    """errors: list of {type,bbox,kind: FN|FP}. Returns list of (error, cause, partner_type)."""
    fns = [e for e in errors if e["kind"] == "FN"]; fps = [e for e in errors if e["kind"] == "FP"]
    out = []
    for e in fns:
        best = max(fps, key=lambda p: iou(tuple(e["bbox"]), tuple(p["bbox"])), default=None)
        v = iou(tuple(e["bbox"]), tuple(best["bbox"])) if best else 0
        if best and v > 0.3:
            out.append((e, "localisation" if best["type"] == e["type"] else "confusion", best["type"]))
        else:
            out.append((e, "missed", None))
    for p in fps:
        v = max((iou(tuple(p["bbox"]), tuple(e["bbox"])) for e in fns), default=0)
        if v <= 0.3:
            out.append((p, "spurious", None))
    return out


def summarize(failures):
    by_page = defaultdict(list)
    for f in failures:
        by_page[(f.get("condition") or f.get("arm"), f.get("seed") or f.get("doc"))].append(f)
    causes = Counter(); confusions = Counter(); per_cond = defaultdict(Counter)
    for (cond, _), errs in by_page.items():
        for e, cause, partner in classify(errs):
            causes[(cause, e["type"])] += 1
            per_cond[cond][cause] += 1
            if cause == "confusion":
                confusions[(e["type"], partner)] += 1
    return causes, confusions, per_cond


def pdf_consistency(pdf, pages=(1, 12), dpi=150):
    """Real-font check without hand labels: score the Tesseract-on-pixels path against the PDF-text-layer path.
    Pseudo ground truth uses the same layout rules, so this isolates OCR/pixel-path degradation on real documents."""
    from .ingest import load_pages
    from .pipeline import process_image
    from .eval import score_page, aggregate
    S, rows = [], []
    for no, pil, native in load_pages(pdf, dpi, max(pages) + 1, True):
        if no not in pages or native is None:
            continue
        ref = process_image(pil, no, native_words=native)
        gt = {"elements": [{"type": e.type if e.type not in ("list_item", "code") else "paragraph", "bbox": list(e.bbox), "text": e.text or ""}
                           for e in sorted(ref.elements, key=lambda e: e.order)],
              "tables": [{"cells": e.cells} for e in ref.elements if e.type == "table"],
              "forms": [{"key": e.key, "value": e.value} for e in ref.elements if e.type == "form_field"]}
        hyp = process_image(pil, no)
        for e in hyp.elements:
            if e.type in ("list_item", "code"):
                e.type = "paragraph"
        s = score_page(hyp, gt); S.append(s)
        rows.append({"page": no + 1, "errors": s["errors"], "page_cer": round(s["page_cer"], 4)})
    return aggregate(S) if S else None, rows


def write_report(results_dir, pdf=None):
    path = os.path.join(results_dir, "failures.json")
    failures = json.load(open(path))
    causes, confusions, per_cond = summarize(failures)
    L = ["# Failure analysis", "",
         "Generated by `python -m docvision.failure_analysis`; every number below is computed from `failures.json`, never typed.", ""]
    L += ["## Synthetic benchmark: what went wrong, by cause and class", "", "| Cause | Class | Count |", "|---|---|---|"]
    for (c, t), n in sorted(causes.items(), key=lambda kv: -kv[1]):
        L.append(f"| {c} | {t} | {n} |")
    if not causes:
        L.append("| (none) | | 0 |")
    L += ["", "**Class confusions (true -> predicted)**", ""]
    L += [f"- {a} -> {b}: {n}" for (a, b), n in confusions.most_common()] or ["- none"]
    L += ["", "**By condition**", "", "| Condition | " + " | ".join(["confusion", "localisation", "missed", "spurious"]) + " |", "|---|---|---|---|---|"]
    for cond, c in per_cond.items():
        L.append(f"| {cond} | " + " | ".join(str(c.get(k, 0)) for k in ("confusion", "localisation", "missed", "spurious")) + " |")
    if pdf:
        agg, rows = pdf_consistency(pdf)
        L += ["", "## Real document: pixel path vs text-layer path (no hand labels)", "",
              "The born-digital PDF is processed twice: from its text layer (reference) and from rendered pixels with Tesseract. "
              "The reference uses the same layout rules, so this measures OCR/pixel degradation on real fonts, not layout correctness.", ""]
        if agg:
            L += [f"Macro-F1 vs reference: **{agg['macro_f1']}**; mean IoU {agg['mean_iou']}.", "",
                  "| Class | P | R | F1 | Support |", "|---|---|---|---|---|"]
            L += [f"| {c} | {v['precision']} | {v['recall']} | {v['f1']} | {v['support']} |" for c, v in agg["classes"].items() if v["support"]]
            for r in rows:
                cz = Counter(c for _, c, _ in classify(r["errors"]))
                L.append(f"\nPage {r['page']}: page CER {r['page_cer']}; error causes {dict(cz) or 'none'}")
    open(os.path.join(results_dir, "FAILURES.md"), "w").write("\n".join(L) + "\n")
    return "\n".join(L)


if __name__ == "__main__":
    ap = argparse.ArgumentParser(); ap.add_argument("--results", default="results"); ap.add_argument("--pdf")
    a = ap.parse_args(); print(write_report(a.results, a.pdf))
